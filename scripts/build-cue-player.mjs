#!/usr/bin/env node
// Builds the cue-sheet player Vibo Community embeds (src/cuePlayer/main.tsx):
// one minified script + one stylesheet, the app's own CueClipOverlay and
// CueOverlay inside. The Community server inlines both into its player page
// (`/cue-sheets/{id}/player`), so the output goes into that repo:
//
//   node scripts/build-cue-player.mjs                       # → dist/cue-player/
//   node scripts/build-cue-player.mjs --out ../viboplr-community/src/cue_player
//
// Rebuild and re-vendor whenever the clip renderer changes, or the site's
// player falls behind the app.
import { build } from "esbuild";
import { execSync } from "node:child_process";
import { resolve } from "node:path";

const outArg = process.argv.indexOf("--out");
const outdir = resolve(outArg > 0 ? process.argv[outArg + 1] : "dist/cue-player");
let rev = "unknown";
try {
  rev = execSync("git rev-parse --short HEAD", { encoding: "utf8" }).trim();
} catch (e) {
  console.error("Could not read the git revision:", e.message);
}
const banner = `/* Vibo cue-sheet player — generated by ViboPLR scripts/build-cue-player.mjs at ${rev}. Do not edit; rebuild. */`;

await build({
  entryPoints: { "cue-player": "src/cuePlayer/main.tsx" },
  outdir,
  bundle: true,
  minify: true,
  format: "iife",
  target: ["es2020", "safari15"],
  jsx: "automatic",
  define: { "process.env.NODE_ENV": '"production"' },
  legalComments: "none",
  banner: { js: banner, css: banner },
  logLevel: "info",
});
console.log(`cue player → ${outdir}`);
