#!/usr/bin/env node
// Fetch the tracklists of the demo library's real albums from MusicBrainz and
// write them to scripts/lib/demoAlbums.mjs — run once when the album list in
// DEMO_ALBUM_PICKS changes, then commit the result. The generator never hits
// the network: the demo library must rebuild identically offline.
//
// Only metadata comes from here (titles, durations, years). The audio is
// still synthesised (make-demo-library.mjs); covers, artist photos and bios
// are fetched by the app's own providers, as for any user's library.
//
// MusicBrainz asks for a descriptive User-Agent and at most one request per
// second; both are honoured.
//
// Usage: node scripts/fetch-demo-tracklists.mjs

import { writeFileSync } from "node:fs";
import { DEMO_ALBUM_PICKS } from "./lib/demoAlbumPicks.mjs";

const UA = "ViboplrDemoLibrary/1.0 ( https://viboplr.com )";
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
let last = 0;

async function mb(path) {
  const wait = last + 1100 - Date.now();
  if (wait > 0) await sleep(wait);
  last = Date.now();
  const res = await fetch(`https://musicbrainz.org/ws/2/${path}${path.includes("?") ? "&" : "?"}fmt=json`, {
    headers: { "User-Agent": UA, Accept: "application/json" },
  });
  if (!res.ok) throw new Error(`MusicBrainz ${res.status} for ${path}`);
  return res.json();
}

const q = (s) => `"${s.replace(/"/g, '\\"')}"`;

/** Straight quotes and plain dashes: the titles end up in file names and in
 *  history keys, where typographic punctuation only causes mismatches. */
const tidy = (s) => s.replace(/[‘’]/g, "'").replace(/[“”]/g, '"').replace(/[‐-―]/g, "-").replace(/…/g, "...");

/** The release that best represents the album as people know it: the
 *  tracklist length most official releases share (deluxe reissues and
 *  mono+stereo sets are the outliers), then one medium, CD or digital,
 *  earliest date. */
function pickRelease(releases) {
  const count = (r) => (r.media ?? []).reduce((n, m) => n + (m["track-count"] ?? m.tracks?.length ?? 0), 0);
  const freq = new Map();
  for (const r of releases) freq.set(count(r), (freq.get(count(r)) ?? 0) + 1);
  const score = (r) => {
    const media = r.media ?? [];
    const formatOk = media.every((m) => /CD|Digital/i.test(m.format ?? ""));
    return [-(freq.get(count(r)) ?? 0), media.length === 1 ? 0 : 1, formatOk ? 0 : 1, r.date || "9999"];
  };
  return [...releases].sort((a, b) => {
    const [x, y] = [score(a), score(b)];
    for (let i = 0; i < x.length; i++) if (x[i] !== y[i]) return x[i] < y[i] ? -1 : 1;
    return 0;
  })[0];
}

const norm = (s) => tidy(s).toLowerCase();

async function fetchAlbum({ artist, title }) {
  const rg = await mb(`release-group/?query=${encodeURIComponent(`releasegroup:${q(title)} AND artist:${q(artist)} AND primarytype:album`)}&limit=10`);
  // Exact title, credited to the artist, no secondary type (live, soundtrack,
  // compilation…) first; the search's own ranking breaks ties.
  const groups = (rg["release-groups"] ?? []).filter((g) => norm(g.title) === norm(title)
    && (g["artist-credit"] ?? []).some((c) => norm(c.name ?? c.artist?.name ?? "") === norm(artist)));
  groups.sort((a, b) => (a["secondary-types"]?.length ?? 0) - (b["secondary-types"]?.length ?? 0));
  for (const group of groups) {
    const rel = await mb(`release?release-group=${group.id}&status=official&inc=recordings+media&limit=100`);
    const release = pickRelease(rel.releases ?? []);
    if (!release) continue;
    const tracks = release.media.flatMap((m) => m.tracks ?? []).map((t) => ({
      title: tidy(t.title),
      durationSecs: Math.round((t.length ?? t.recording?.length ?? 240000) / 1000),
    }));
    const year = Number((group["first-release-date"] ?? release.date ?? "").slice(0, 4)) || null;
    console.log(`  ${artist} – ${title} (${year}): ${tracks.length} tracks`);
    return { artist, title, year, tracks };
  }
  throw new Error(`no official release for ${artist} – ${title}`);
}

const out = [];
for (const pick of DEMO_ALBUM_PICKS) out.push({ ...pick, ...(await fetchAlbum(pick)) });

writeFileSync(new URL("./lib/demoAlbums.mjs", import.meta.url), [
  "// Generated by scripts/fetch-demo-tracklists.mjs from MusicBrainz — do not edit by hand;",
  "// change DEMO_ALBUM_PICKS in demoAlbumPicks.mjs and re-run the script.",
  `export const DEMO_ALBUMS = ${JSON.stringify(out, null, 2)};`,
  "",
].join("\n"));
console.log(`Wrote ${out.length} albums.`);
